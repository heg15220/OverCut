/**
 * Camera zones: where along the lap the TV director cuts (F1M24-GAMEPLAY §2.5 camera-zones,
 * CAM-2; RF-3D-03, RF-3D-04, RNF-05, RNF-07). Pure: no three.js, no React, no randomness
 * beyond the race seed, so the engine loader (tools/assets/engine_loader.mjs) can run it from
 * Node and the director (components/director) can share it.
 *
 * A real broadcast hands the car from camera to camera by where it is, not by the clock: the
 * cuts fall at the same fractions of the lap lap after lap, and a shot lasts as long as the car
 * takes to cross its stretch - short in the slow corners, long on the straights. So the lap is
 * split into zones (each corner or chicane, the braking area at the end of the long straights,
 * pieces of straight, the start line), each with one to three alternative cameras; on entering a
 * zone the director picks one of them by weight with the race seed, never the one it used in that
 * zone the lap before (data/balance/broadcast.json zonesPolicy).
 *
 *   buildCameraZones(circuit) → { lengthM, zones: [{ fromM, toM, kind, corners?, cams: [{ type, atM, side, cornerKind? }] }] }
 *   zonesFor(circuit)        → the zones of data/circuits/<splineId>/camera-zones.json when the
 *                              circuit has a file (generated by tools/assets/camera_zones.mjs, hand
 *                              editable), the built ones otherwise
 *   pickVariant(cams, { seed, zoneIndex, lap })  → index of the camera on air
 *
 * Metres are along the lap from the line; a zone across the line has toM > lengthM. A camera's
 * `atM` is its anchor (apex, end of the straight, middle of the piece); three/cameras.js
 * buildZoneRig turns it into a position with the rigTemplate of broadcast.json.
 */

import broadcast from "../data/balance/broadcast.json";
import zoneFiles from "../data/circuits/cameraZones";

const TEMPLATE = new Map(broadcast.rigTemplate.types.map((entry) => [entry.type, entry]));
/** The rigTemplate entry of a trackside camera type. */
export const rigType = (type) => TEMPLATE.get(type) || null;

const mod = (value, length) => ((value % length) + length) % length;
const round = (value) => Math.round(value * 10) / 10;

/** FNV-1a of a text. */
const fnv = (text) => {
  let h = 0x811c9dc5;
  const str = String(text);
  for (let i = 0; i < str.length; i += 1) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
};
const hash01 = (seed, n) => {
  let h = (seed ^ Math.imul(n | 0, 0x27d4eb2d)) >>> 0;
  h = Math.imul(h ^ (h >>> 15), 0x85ebca6b);
  h = Math.imul(h ^ (h >>> 13), 0xc2b2ae35);
  h ^= h >>> 16;
  return (h >>> 0) / 4294967296;
};

/** The race seed mixed with the zones' salt (a race seed number or any text). */
export const zoneSeed = (seed, policy = broadcast.zonesPolicy) => (fnv(policy.seedSalt) ^ (typeof seed === "number" ? seed >>> 0 : fnv(seed ?? ""))) >>> 0;

/**
 * The camera of a zone on a lap: a weighted draw on (seed, zone, lap); with `avoidRepeat` never
 * the camera that zone had the lap before (the chain is walked from lap 0, so the answer depends
 * only on the seed, the zone and the lap - not on what the viewer watched before; RNF-05).
 */
export const pickVariant = (cams, { seed = 0, zoneIndex = 0, lap = 0 } = {}, policy = broadcast.zonesPolicy) => {
  if (!cams?.length) return -1;
  if (cams.length === 1) return 0;
  const weights = cams.map((cam) => Math.max(0, cam.weight ?? rigType(cam.type)?.weight ?? 1));
  const salted = zoneSeed(seed, policy);
  let prev = -1;
  let pick = 0;
  const last = Math.max(0, Math.floor(Number.isFinite(lap) ? lap : 0));
  for (let l = 0; l <= last; l += 1) {
    const allowed = [];
    for (let i = 0; i < cams.length; i += 1) if (!policy.avoidRepeat || i !== prev) allowed.push(i);
    const total = allowed.reduce((sum, i) => sum + weights[i], 0);
    const r = hash01(salted, Math.imul(zoneIndex + 1, 65537) + l);
    if (total <= 0) pick = allowed[Math.floor(r * allowed.length)];
    else {
      let left = r * total;
      pick = allowed[allowed.length - 1];
      for (const i of allowed) {
        left -= weights[i];
        if (left < 0) {
          pick = i;
          break;
        }
      }
    }
    prev = pick;
  }
  return pick;
};

const camsOf = (kind, policy, anchor) => policy.cams[kind].map((type) => ({ type, ...anchor(type) }));

/**
 * The zones of a circuit, from its geometry: corners closer than chicaneGapM are one zone
 * (cornerEntryM before the first, cornerExitM after the last; two zones that would overlap meet
 * half way); the braking area (rigTemplate braking.approach) before the corners that end the
 * long straights (circuit.brakingZones); what is left of each straight in pieces of at most
 * straightMaxM; a piece shorter than minZoneM joins its neighbour. The piece of straight across
 * the line is the `line` zone.
 */
export const buildCameraZones = (circuit, policy = broadcast.zonesPolicy) => {
  const L = circuit.length;
  const { cornerEntryM, cornerExitM, chicaneGapM, straightMaxM, minZoneM } = policy.layout;
  const braking = rigType("braking");
  const sideOf = (corner) => -(corner?.sign || 1);
  const straightSide = (m) => (Math.round((mod(m, L) / L) * 97) % 2 ? 1 : -1);
  const raw = [];
  const straightPieces = (from, to) => {
    const length = to - from;
    if (length <= 0) return;
    const count = Math.max(1, Math.ceil(length / straightMaxM));
    for (let k = 0; k < count; k += 1) {
      const a = from + (length * k) / count;
      const b = from + (length * (k + 1)) / count;
      const mid = (a + b) / 2;
      raw.push({ from: a, to: b, kind: "straight", cams: camsOf("straight", policy, () => ({ atM: mid, side: straightSide(mid) })) });
    }
  };

  const corners = (circuit.corners || []).slice().sort((a, b) => a.from - b.from);
  const groups = [];
  corners.forEach((corner) => {
    const last = groups[groups.length - 1];
    if (last && corner.from * L - last.endM < chicaneGapM) {
      last.endM = Math.max(last.endM, corner.to * L);
      last.corners.push(corner);
    } else groups.push({ startM: corner.from * L, endM: corner.to * L, corners: [corner] });
  });
  if (groups.length > 1) {
    const first = groups[0];
    const last = groups[groups.length - 1];
    if (first.startM + L - last.endM < chicaneGapM) {
      last.endM = Math.max(last.endM, first.endM + L);
      last.corners.push(...first.corners);
      groups.shift();
    }
  }

  if (!groups.length) straightPieces(0, L);
  const n = groups.length;
  groups.forEach((group) => {
    group.from = group.startM - cornerEntryM;
    group.to = group.endM + cornerExitM;
  });
  groups.forEach((group, i) => {
    const next = groups[(i + 1) % n];
    const shift = i === n - 1 ? L : 0;
    if (n > 1 && group.to > next.from + shift) {
      const mid = (group.endM + next.startM + shift) / 2;
      group.to = mid;
      next.from = mid - shift;
    } else if (n === 1 && group.to > group.from + L) group.to = group.from + L;
  });
  groups.forEach((group, i) => {
    const next = groups[(i + 1) % n];
    const shift = i === n - 1 ? L : 0;
    const apex = group.corners.reduce((best, corner) => (corner.kmh < best.kmh ? corner : best), group.corners[0]);
    const zone = {
      from: group.from,
      to: group.to,
      kind: "corner",
      corners: group.corners.map((corner) => corner.number),
      cams: camsOf("corner", policy, () => ({ atM: apex.apex * L, side: sideOf(apex), cornerKind: apex.kind })),
    };
    raw.push(zone);
    // The straight up to the next group: braking area at its end when a long straight ends there.
    const gapFrom = group.to;
    const gapTo = next.from + shift;
    if (gapTo - gapFrom <= 0) return;
    const target = next.corners[0];
    const brake = (circuit.brakingZones || []).find((item) => next.corners.some((corner) => corner.number === item.corner));
    let straightTo = gapTo;
    if (brake && braking) {
      const approach = Math.min(braking.approach.maxShare * L, braking.approach.ofStraight * brake.metres);
      let from = Math.max(gapFrom, gapTo - approach);
      if (from - gapFrom < minZoneM) from = gapFrom;
      raw.push({ from, to: gapTo, kind: "braking", cams: camsOf("braking", policy, () => ({ atM: gapTo, side: sideOf(target) })) });
      straightTo = from;
    }
    if (straightTo - gapFrom <= 0) return;
    if (straightTo - gapFrom < minZoneM) {
      // Too short for a shot of its own: the corner zone runs on to it.
      zone.to = straightTo;
      return;
    }
    straightPieces(gapFrom, straightTo);
  });

  // The start line: the stretch the grandstand camera covers (rigTemplate grandstand.spanM) is
  // carved out of the straight or braking zone it falls in and filmed as the `line` zone; what is
  // left of that zone, if shorter than minZoneM, goes to the line zone too. Not inside a corner.
  const lineSide = circuit.clockwise ? -1 : 1;
  const span = rigType("grandstand")?.spanM;
  let placed = raw.map((zone) => ({ ...zone, fromM: mod(zone.from, L), length: zone.to - zone.from }));
  if (span && policy.cams.line?.length) {
    let lineFrom = span.from;
    let lineTo = span.to;
    const touches = (zone, shift) => zone.fromM + shift < lineTo && zone.fromM + zone.length + shift > lineFrom;
    const hit = placed.filter((zone) => touches(zone, 0) || touches(zone, -L));
    if (hit.length && hit.every((zone) => zone.kind !== "corner")) {
      const rest = [];
      hit.forEach((zone) => {
        const shift = touches(zone, 0) ? 0 : -L;
        const a = zone.fromM + shift;
        const b = a + zone.length;
        if (lineFrom - a >= minZoneM) rest.push({ ...zone, fromM: mod(a, L), length: lineFrom - a });
        else lineFrom = Math.min(lineFrom, a);
        if (b - lineTo >= minZoneM) rest.push({ ...zone, fromM: mod(lineTo, L), length: b - lineTo });
        else lineTo = Math.max(lineTo, b);
      });
      const mid = (lineFrom + lineTo) / 2;
      placed = placed.filter((zone) => !hit.includes(zone)).concat(rest, {
        kind: "line",
        fromM: mod(lineFrom, L),
        length: lineTo - lineFrom,
        cams: camsOf("line", policy, (type) => (type === "grandstand" ? { atM: 0, side: lineSide } : { atM: mid, side: straightSide(mid) })),
      });
    }
  }
  const zones = placed
    .sort((a, b) => a.fromM - b.fromM)
    .map((zone) => {
      const out = { fromM: round(zone.fromM), toM: round(zone.fromM + zone.length), kind: zone.kind };
      if (zone.corners) out.corners = zone.corners;
      out.cams = zone.cams.map((cam) => {
        const entry = { type: cam.type, atM: round(mod(cam.atM, L)), side: cam.side };
        if (cam.type === "corner" && cam.cornerKind) entry.cornerKind = cam.cornerKind;
        return entry;
      });
      return out;
    });
  return { lengthM: round(L), zones };
};

/**
 * The zones a circuit is filmed with: its file under data/circuits/ (by splineId) when there is
 * one, the built ones otherwise. A file is in the metres of the spline it was made from; on a
 * circuit of another length it is scaled to it.
 */
export const zonesFor = (circuit, files = zoneFiles) => {
  const file = circuit?.splineId ? files[circuit.splineId] : null;
  if (file && file.splineId === circuit.splineId && file.zones?.length) return { lengthM: file.lengthM, zones: file.zones, source: "file" };
  return { ...buildCameraZones(circuit), source: "built" };
};

const inSpan = (share, from, to) => {
  const s = mod(share, 1);
  const a = mod(from, 1);
  const b = mod(to, 1);
  return a <= b ? s >= a && s <= b : s >= a || s <= b;
};

/**
 * On a zone rig (three/cameras.js buildZoneRig: cameras with `zone`, `variant`, `weight`, `from`,
 * `to` in lap shares), the cameras of the zone holding `share`, the one on air this lap first
 * (pickVariant), the others by weight after it (for when the first cannot see the car). Null when
 * no zone camera holds the share (a rig by priority).
 */
export const zoneChoice = (rig, share, lap, seed) => {
  const holding = (rig || []).filter((cam) => cam.zone !== undefined && inSpan(share, cam.from, cam.to));
  if (!holding.length) return null;
  // On a boundary two zones hold the share: the one that starts there.
  const zone = holding.reduce((best, cam) => (mod(share - cam.from, 1) < mod(share - best.from, 1) ? cam : best), holding[0]).zone;
  const cams = rig.filter((cam) => cam.zone === zone).sort((a, b) => a.variant - b.variant);
  const pick = pickVariant(cams, { seed, zoneIndex: zone, lap });
  const rest = cams.filter((_, i) => i !== pick).sort((a, b) => b.weight - a.weight || a.variant - b.variant);
  return [cams[pick], ...rest];
};

/** Index of the zone that holds a share of the lap (-1 if none). */
export const zoneIndexAt = (zones, share, lengthM = zones.lengthM) => {
  const m = mod(share, 1) * lengthM;
  return zones.zones.findIndex((zone) => (m >= zone.fromM && m < zone.toM) || (zone.toM > lengthM && m < zone.toM - lengthM));
};
